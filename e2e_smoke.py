import os,time,sys
from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b=p.chromium.launch(args=['--use-gl=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist'])
    pg=b.new_page(viewport={'width':1436,'height':840})
    logs=[]; pg.on('pageerror',lambda e: logs.append('PAGEERR '+str(e)[:300])); pg.on('console',lambda m: logs.append('C '+m.text[:200]) if m.type=='error' else None)
    pg.goto('http://localhost:8765/index.html',timeout=120000)
    pg.wait_for_function("window.__tt && window.__tt.state==='profile'",timeout=150000); time.sleep(2)
    pg.fill('#pName','Biraj')
    pg.click('#codeBtn'); time.sleep(.4); pg.keyboard.type('turbo4k'); time.sleep(.3)
    pg.screenshot(path='t63_1_join.png')
    pg.fill('#jCode','ab'); pg.click('#jGo'); print('err short:',pg.inner_text('#jErr'))
    pg.click('#jX'); time.sleep(.3)
    pg.click('#goBtn'); time.sleep(1.2); pg.screenshot(path='t63_2_room_early.png')
    print('code',pg.inner_text('#rcTxt'))
    time.sleep(5); pg.click('#startBtn'); time.sleep(.6); pg.screenshot(path='t63_3_ready.png')
    print('btn',pg.inner_text('#startBtn').replace('\n',' '), '| msg', pg.inner_text('#roomMsg').replace('\n',' '))
    pg.wait_for_function("window.__tt.state==='racing'",timeout=120000); time.sleep(1)
    w=pg.evaluate("window.__tt.cur.words.slice(0,3).map(x=>x.t).join(' ')")
    pg.keyboard.type(w[:10],delay=40)
    pg.keyboard.press('Shift+X'); time.sleep(.3)
    pg.evaluate("window.__tt.dbg.give('shield'); window.__tt.dbg.give('freeze'); window.__tt.racers[1].dbT=4; window.__tt.racers[1].dbKind='ink'; window.__tt.racers[2].dbT=3;window.__tt.racers[2].dbKind='torpedo'"); time.sleep(1)
    pg.screenshot(path='t63_4_race.png')
    print('pos',pg.inner_text('#pos'),'lap',pg.inner_text('#lap'),'time',pg.inner_text('#timer'))
    pg.evaluate("window.__tt.finishNow()")
    pg.wait_for_function("!document.getElementById('results').hidden",timeout=120000); time.sleep(1.5)
    pg.screenshot(path='t63_5_results.png')
    pg.click('#garageBtn'); time.sleep(1.5); print('new code',pg.inner_text('#rcTxt'))
    pg.click('#backBtn'); time.sleep(.5)
    pg.click('#codeBtn'); time.sleep(.3); pg.keyboard.type('XXXXXXX'); pg.click('#jGo'); time.sleep(.5); print('after join:', pg.evaluate("window.__tt.state"))
    print('\n'.join(logs[:20])); b.close()
